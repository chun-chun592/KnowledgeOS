from __future__ import annotations

import re
from typing import Iterable
from .schema import Document

START_MARKER = '<!-- knowledgeos:index:start -->'
END_MARKER = '<!-- knowledgeos:index:end -->'
TYPE_ORDER = ("concept", "entity", "topic", "comparison", "synthesis", "project", "decision", "source", "unclassified")
TYPE_LABELS = {
    "concept": "Concepts",
    "entity": "Entities",
    "topic": "Topics",
    "comparison": "Comparisons",
    "synthesis": "Synthesis",
    "project": "Projects",
    "decision": "Decisions",
    "source": "Sources",
    "unclassified": "Unclassified",
}


def _summary(document: Document, limit: int = 100) -> str:
    quote = ""
    for line in document.body.splitlines():
        stripped = line.strip()
        if stripped.startswith("> "):
            quote = stripped[2:].strip()
            break
    if not quote:
        for line in document.body.splitlines():
            stripped = line.strip()
            if not stripped or stripped.startswith(("#", "|", "```", ">", "-", "*", "<!--")):
                continue
            quote = stripped
            break
    quote = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", quote)
    quote = re.sub(r"\[\[([^\]]+)\]\]", r"\1", quote)
    quote = re.sub(r"[*_`]", "", quote).replace("|", "\\|")
    return quote[:limit].strip()


def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def render_block(pages: Iterable[Document]) -> str:
    page_list = sorted(pages, key=lambda doc: (TYPE_ORDER.index(doc.note_type) if doc.note_type in TYPE_ORDER else 99, doc.title.casefold()))
    lines: list[str] = [START_MARKER, ""]
    lines.append("> Generated by `knowledgeos index`. Edit only outside this block; manual edits inside will be overwritten.")
    lines.append("")

    counts: dict[str, int] = {name: 0 for name in TYPE_ORDER}
    for document in page_list:
        counts[document.note_type if document.note_type in TYPE_ORDER else "unclassified"] += 1

    lines.append("## Statistics")
    lines.append("")
    lines.append("| Type | Pages |")
    lines.append("| --- | ---: |")
    for type_name in TYPE_ORDER:
        lines.append(f"| {type_name} | {counts.get(type_name, 0)} |")
    lines.append(f"| **total** | **{len(page_list)}** |")
    lines.append("")

    grouped: dict[str, list[Document]] = {}
    for document in page_list:
        grouped.setdefault(document.note_type if document.note_type in TYPE_ORDER else "unclassified", []).append(document)

    for type_name in TYPE_ORDER:
        documents = grouped.get(type_name, [])
        lines.append(f"## {TYPE_LABELS[type_name]}")
        lines.append("")
        if not documents:
            lines.append("_No pages yet._")
            lines.append("")
            continue
        lines.append("| Page | Summary | Status | Updated |")
        lines.append("| --- | --- | --- | --- |")
        for document in sorted(documents, key=lambda doc: doc.title.casefold()):
            link_target = document.rel.removesuffix(".md")
            row = (
                f"| [[{link_target}\\|{_cell(document.title)}]] "
                f"| {_cell(_summary(document))} "
                f"| `{_cell(document.status or 'unknown')}` "
                f"| {_cell(str(document.frontmatter.get('updated', '') or ''))} |"
            )
            lines.append(row)
        lines.append("")

    lines.append("_Generated by the KnowledgeOS indexer. Do not edit inside this block._")
    lines.append("")
    lines.append(END_MARKER)
    return "\n".join(lines)
